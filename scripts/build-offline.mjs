import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const distDir = path.join(rootDir, 'dist');
const distHtmlPath = path.join(distDir, 'index.html');
const offlineHtmlPath = path.join(rootDir, 'JEJAK-JKN-Demo-Offline.html');

if (!fs.existsSync(distHtmlPath)) {
  throw new Error('dist/index.html tidak ditemukan. Jalankan "vite build" terlebih dahulu.');
}

let html = fs.readFileSync(distHtmlPath, 'utf8');

// Inline all local CSS links generated by Vite
html = html.replace(
  /<link[^>]+rel=["']stylesheet["'][^>]+href=["']([^"']+)["'][^>]*>/gi,
  (_match, href) => {
    const assetRel = href.replace(/^\.?\//, '');
    const cssPath = path.join(distDir, assetRel);
    const cssContent = fs.readFileSync(cssPath, 'utf8');
    return `<style>\n${cssContent}\n</style>`;
  }
);

// Extract all bundled JS scripts generated by Vite and place inline at end of <body>
const inlineScripts = [];
html = html.replace(
  /<script[^>]+src=["']([^"']+)["'][^>]*><\/script>/gi,
  (_match, src) => {
    const assetRel = src.replace(/^\.?\//, '');
    const jsPath = path.join(distDir, assetRel);
    const jsContent = fs
      .readFileSync(jsPath, 'utf8')
      .replace(/<\/script/gi, '<\\/script');
    const wrapped = `(function(){\n'use strict';\n${jsContent}\n})();`;
    // Verify valid JS syntax before writing offline HTML
    new vm.Script(wrapped);
    inlineScripts.push(`<script>\n${wrapped}\n</script>`);
    return '';
  }
);

// Remove modulepreload hints if any
html = html.replace(/<link[^>]+rel=["']modulepreload["'][^>]*>/gi, '');

if (inlineScripts.length > 0) {
  // IMPORTANT: Use replacer function so '$' characters in minified JS are never interpreted as regex patterns!
  html = html.replace('</body>', () => `${inlineScripts.join('\n')}\n</body>`);
}

fs.writeFileSync(offlineHtmlPath, html, 'utf8');
const stats = fs.statSync(offlineHtmlPath);
console.log(
  `[build-offline] Berhasil memperbarui JEJAK-JKN-Demo-Offline.html (${(stats.size / 1024).toFixed(1)} KB, sintaks JS terverifikasi, 100% mandiri).`
);
